def canonical_genres(raw_labels: Iterable[str], *, animated: bool = False) -> list[str]:
    found: set[str] = set()
    for raw in raw_labels:
        label = raw.lower().strip()
        for genre, stems in CANONICAL_GENRES.items():
            if genre == "драма" and "мелодрам" in label:
                continue  # «мелодрама» — это не «драма»
            if any(stem in label for stem in stems):
                found.add(genre)
    if animated:
        found.add("мультфильм")
    return [g for g in CANONICAL_GENRES if g in found]
